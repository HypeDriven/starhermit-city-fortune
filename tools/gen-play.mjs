// Writes tests/native/*.play from the rules: a journey stage played to its
// results by the simple bot the rules tests use (buy what the hint says to
// buy, skip the rest, roll otherwise), each command a key (Enter rolls, B
// buys, N skips) followed by C (skip animations) and a short wait, so the
// script does not depend on the presentation's timing. Run after changing
// the rules or the content: node tools/gen-play.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const Content = require('../js/content.js');
const Game = require('../js/game.js');

// Each step is a list of play-script lines. Rolls click the Roll button; a
// build moves the selection there with the arrow keys and confirms (Enter
// builds on a selected buildable tile); B buys and N skips the offer.
function plan(cfg, builds) {
  const sess = Game.createSession(cfg, null, 0);
  const n = cfg.tiles.length;
  const steps = [];
  let selected = null;
  let k = 0;
  while (!sess.state.terminal && k < 400) {
    const s = sess.state;
    let cmd, lines;
    if (s.phase === 'buy') {
      const h = Game.hint(s);
      cmd = { type: h && h.type === 'buy' ? 'buy' : 'skip' };
      lines = [`key ${cmd.type === 'buy' ? 'KeyB' : 'KeyN'} 1`];
    } else {
      const b = builds ? Game.legalActions(s).find((a) => a.type === 'build') : null;
      if (b && s.you.coins > b.cost * 3) {
        cmd = { type: 'build', tile: b.tile };
        const from = selected == null ? s.you.pos : selected;
        const fwd = ((b.tile - from) % n + n) % n;
        lines = [];
        if (fwd <= n - fwd) for (let i = 0; i < fwd; i++) lines.push('key ArrowRight 1', 'frames 2');
        else for (let i = 0; i < n - fwd; i++) lines.push('key ArrowLeft 1', 'frames 2');
        // (already selected: step off and back, which also takes the focus off the tray)
        if (fwd === 0) lines.push('key ArrowRight 1', 'frames 2', 'key ArrowLeft 1', 'frames 2');
        selected = b.tile;
        lines.push('key Enter 1');
      } else {
        cmd = { type: 'roll' };
        lines = ['frames 5', 'click Roll'];
      }
    }
    const r = Game.applyToSession(sess, cmd, 1000 + k * 1200);
    if (!r.ok) throw new Error('bot command rejected: ' + r.reason);
    if (sess.state.phase === 'buy' && sess.state.pending) selected = sess.state.pending.tile;
    steps.push(lines);
    k++;
  }
  return { steps, won: !!(sess.state.terminal && sess.state.terminal.won), score: sess.state.score.total };
}

function script(cfg, file, label, after, builds) {
  const p = plan(cfg, builds);
  if (!p.won) throw new Error(cfg.id + ': the bot does not win');
  const lines = [
    `# Generated by tools/gen-play.mjs: ${label} played to its`,
    `# results by the rules tests' bot — ${p.steps.length} commands (Roll clicked, B buys, N skips,`,
    `# arrows + Enter build), each followed by C (skip animations); the album completes.`,
    'until 300 City Fortune',
    'frames 20',
    'click Play',
    'until 60 Choose a mode',
    'frames 10',
    `click ${cfg.name}`,
    'until 60 Expected duration',
    'frames 10',
    'click Start',
    'until 120 Your turn',
    'frames 30',
  ];
  p.steps.forEach((st, i) => {
    lines.push(...st, 'frames 3', 'key KeyC 1', 'frames 6');
    if (i === Math.floor(p.steps.length / 2)) lines.push('save mid-round');
  });
  lines.push('until 300 Album complete!', 'frames 10', 'expect Rent collected', ...after, 'save results');
  writeFileSync(new URL(`../tests/native/${file}`, import.meta.url), lines.join('\n') + '\n');
  console.log(`${file}: ${p.steps.length} commands, score ${p.score}`);
}

script(Content.JOURNEY[0], 'journey-first-steps.play', 'journey stage 1 (First Steps)', ['expect Next: ' + Content.JOURNEY[1].name], false);
script(Content.PRACTICE[1], 'practice-rival.play', 'the Standard practice board (with the rival Penny)', ['expect Retry'], true);
